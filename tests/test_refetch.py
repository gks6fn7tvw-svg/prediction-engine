"""The network verifier, run against a fake Kalshi and a fake NOAA S3.

The Kalshi side replays ChatGPT's saved responses. The NOAA side is synthetic: real
GRIB bytes aren't in the repo, so the fixture's message and index hashes are rewritten
to match generated bytes. That tests the verifier's logic, not NOAA's data.
"""
import hashlib
import json
import shutil
import tempfile
import unittest
from datetime import datetime, timedelta, timezone
from pathlib import Path
