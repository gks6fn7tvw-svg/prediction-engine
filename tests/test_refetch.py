class RetryClassificationTests(unittest.TestCase):
    """Every 5xx and 429 is retryable; other answers are confirmed (ChatGPT #10)."""

    def classify(self, status):
        clock = FakeClock(datetime(2026, 11, 11, tzinfo=timezone.utc))
        net = Net(lambda *a: (status, {}, b""), clock)
        try:
            net.get("https://example.test/x")
        except TransientError:
            return "retry"
        except SourceError:
            return "confirmed"
        return "ok"

    def test_all_server_errors_and_rate_limits_are_retried(self):
        for status in (429, 500, 501, 502, 503, 504, 505, 507, 520, 529, 599):
            self.assertEqual(self.classify(status), "retry", status)

    def test_client_errors_are_confirmed(self):
        for status in (400, 401, 403, 404, 410, 600):
            self.assertEqual(self.classify(status), "confirmed", status)

    def test_network_exception_is_retried(self):
        clock = FakeClock(datetime(2026, 11, 11, tzinfo=timezone.utc))

        def boom(*a):
            raise OSError("connection reset")
        with self.assertRaises(TransientError):
            Net(boom, clock).get("https://example.test/x")


class PacingTests(unittest.TestCase):
    """Kalshi answered 429 on the first real multi-batch run (19:25 UTC Nov 11)."""

    def setUp(self):
        self.clock = FakeClock(datetime(2026, 11, 11, tzinfo=timezone.utc))
        self.calls = []

    def net(self, answers):
        answers = list(answers)

        def transport(method, url, headers, body, timeout):
            self.calls.append(self.clock.monotonic())
            return answers.pop(0) if answers else (200, {}, b"ok")
        return Net(transport, self.clock)

    def test_kalshi_requests_are_spaced_at_least_a_second_apart(self):
        net = self.net([])
        for _ in range(3):
            net.get("https://external-api.kalshi.com/trade-api/v2/markets?x=1")
        gaps = [b - a for a, b in zip(self.calls, self.calls[1:])]
        self.assertTrue(all(g >= 1.0 for g in gaps), gaps)

    def test_other_hosts_are_not_paced(self):
        net = self.net([])
        net.get("https://noaa-nbm-grib2-pds.s3.amazonaws.com/a")
        net.get("https://noaa-nbm-grib2-pds.s3.amazonaws.com/b")
        self.assertEqual(self.clock.sleeps, [])

    def test_retry_after_is_honoured(self):
        net = self.net([(429, {"Retry-After": "7"}, b""), (200, {}, b"ok")])
        self.assertEqual(net.get("https://external-api.kalshi.com/x")[2], b"ok")
        self.assertIn(7.0, self.clock.sleeps)

    def test_without_retry_after_backoff_grows(self):
        net = self.net([(429, {}, b"")] * 3 + [(200, {}, b"ok")])
        self.assertEqual(net.get("https://external-api.kalshi.com/x")[2], b"ok")
        self.assertEqual([s for s in self.clock.sleeps if s >= 5], [5, 15, 45])

    def test_retry_after_beyond_the_budget_leaves_it_pending_without_waiting(self):
        net = self.net([(429, {"retry-after": "100000"}, b""), (200, {}, b"ok")])
        with self.assertRaises(TransientError):
            net.get("https://external-api.kalshi.com/x")
        self.assertFalse(any(s >= 120 for s in self.clock.sleeps))
        self.assertEqual(len(self.calls), 1)  # no early retry

    def test_retry_after_as_http_date(self):
        when = self.clock.now() + timedelta(seconds=30)
        net = self.net([(503, {"Retry-After": when.strftime("%a, %d %b %Y %H:%M:%S GMT")}, b""),
                        (200, {}, b"ok")])
        net.get("https://external-api.kalshi.com/x")
        self.assertIn(30.0, self.clock.sleeps)

    def test_far_http_date_leaves_it_pending(self):
        when = self.clock.now() + timedelta(hours=2)
        net = self.net([(429, {"Retry-After": when.strftime("%a, %d %b %Y %H:%M:%S GMT")}, b"")])
        with self.assertRaises(TransientError):
            net.get("https://external-api.kalshi.com/x")


class HelperTests(unittest.TestCase):
    def test_nearest_value_picks_the_closest_cell(self):
        lats, lons = np.meshgrid(np.array([40.0, 40.5, 41.0]), np.array([-74.5, -74.0, -73.5]), indexing="ij")
        values = np.arange(9.0).reshape(3, 3)
        self.assertEqual(nearest_value(values, lats, lons, 40.78, -73.97), values[2, 1])
        self.assertEqual(nearest_value(values, lats, lons + 360, 40.1, -74.4), values[0, 0])  # 0..360 lons

    def test_idx_entry(self):
        text = "1:0:d=x:UGRD:10 m:f:\n2:100:d=x:TMP:2 m above ground:f:\n3:250:d=x:DPT:2 m:f:\n"
        self.assertEqual(idx_entry(text, 100), ("2:100:d=x:TMP:2 m above ground:f:", 250))
        self.assertEqual(idx_entry(text, 250)[1], None)
        self.assertEqual(idx_entry(text, 7), (None, None))


