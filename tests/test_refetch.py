from verify.refetch import Net, SourceError, TransientError, Verifier, idx_entry, nearest_value, run_once

FIXTURE = Path(__file__).parent / "fixtures"
BATCH = "history/development/2026-09-11"


def _utc(s):
    return datetime.fromisoformat(s.replace("Z", "+00:00")).astimezone(timezone.utc)


class FakeWorld:
    def __init__(self, root: Path):
        self.root = root
        self.batch = root / BATCH
        self.objects = {}   # s3 key -> {"bytes": b, "last_modified": dt, "etag": str}
        self.kalshi = {}    # url -> bytes
        self.calls = []
        self.kalshi_503s = 0  # answer this many Kalshi requests with HTTP 503 first
        self._build()

    def _rewrite(self, rel, data):
        raw = json.dumps(data).encode()
        (self.batch / rel).write_bytes(raw)
        man = json.loads((self.batch / "manifest.json").read_bytes())
        man["files"][rel] = {"bytes": len(raw), "sha256": hashlib.sha256(raw).hexdigest()}
        (self.batch / "manifest.json").write_bytes(json.dumps(man).encode())

    def _build(self):
        man = json.loads((self.batch / "manifest.json").read_bytes())
        for key, info in man["cities"].items():
            for kind in ("markets", "candles"):
                src = info["kalshi_sources"][kind]
                self.kalshi[src["url"]] = (self.batch / src["path"]).read_bytes()
            nbm_rel = info["forecast_path"]
            nbm = json.loads((self.batch / nbm_rel).read_bytes())
            self.stage_hours(nbm)
            self._rewrite(nbm_rel, nbm)

    def stage_hours(self, nbm):
        """Give each forecast hour synthetic GRIB/index bytes and register them in fake S3."""
        for h in nbm["hours"]:
            s = h["source"]
            # One GRIB message holds the whole CONUS field, so cities sharing a cycle share it.
            msg = f"GRIB-{s['s3_key']}@{s['range_start']}".encode()
            start = s["range_start"]
            s["range_end_inclusive"] = start + len(msg) - 1
            s["message_bytes"] = len(msg)
            s["message_sha256"] = hashlib.sha256(msg).hexdigest()
            idx = (f"1:0:d=x:UGRD:10 m above ground:f:\n"
                   f"2:{start}:d=x:TMP:2 m above ground:f:\n"
                   f"3:{start + len(msg)}:d=x:DPT:2 m above ground:f:\n").encode()
            s["index"]["bytes"], s["index"]["sha256"] = len(idx), hashlib.sha256(idx).hexdigest()
            # The GRIB object is sparse: only the message at its byte range is stored.
            obj = self.objects.setdefault(s["s3_key"], {
                "chunks": {}, "size": s["s3_object_bytes"],
                "last_modified": _utc(s["last_modified_utc"]), "etag": s["etag"]})
            obj["chunks"][start] = msg
            self.objects[s["index"]["s3_key"]] = {
                "bytes": idx, "size": len(idx), "last_modified": _utc(s["index"]["last_modified_utc"]),
                "etag": s["index"]["etag"]}

    def add_later_cycle(self, key: str, published: datetime):
        """Publish a complete later cycle for one city, every file at `published`."""
        nbm = json.loads((self.batch / f"{key}/nbm.json").read_bytes())
        c = _utc(nbm["cycle_utc"]) + timedelta(hours=1)
        for h in nbm["hours"]:
            fh = int((_utc(h["valid_time_utc"]) - c).total_seconds() // 3600)
            base = f"blend.{c:%Y%m%d}/{c:%H}/core/blend.t{c:%H}z.core.f{fh:03d}.co.grib2"
            for k in (base, base + ".idx"):
                self.objects[k] = {"bytes": b"x", "size": 1, "last_modified": published, "etag": '"x"'}

    def __call__(self, method, url, headers, body, timeout):
        self.calls.append(url)
        u = urlparse(url)
        if u.netloc == "external-api.kalshi.com":
            if self.kalshi_503s > 0:
                self.kalshi_503s -= 1
                return 503, {}, b"unavailable"
            return (200, {}, self.kalshi[url]) if url in self.kalshi else (404, {}, b"")
        if u.netloc.endswith(".s3.amazonaws.com"):
            q = parse_qs(u.query)
            if q.get("list-type") == ["2"]:
                prefix = q["prefix"][0]
                rows = "".join(
                    f"<Contents><Key>{k}</Key><LastModified>{o['last_modified']:%Y-%m-%dT%H:%M:%S.000Z}"
                    f"</LastModified><ETag>{o['etag']}</ETag><Size>{o['size']}</Size></Contents>"
                    for k, o in sorted(self.objects.items()) if k.startswith(prefix))
                xml = ('<?xml version="1.0"?><ListBucketResult xmlns="http://s3.amazonaws.com/doc/2006-03-01/">'
                       f"{rows}<IsTruncated>false</IsTruncated></ListBucketResult>")
                return 200, {}, xml.encode()
            key = u.path.lstrip("/")
            if key not in self.objects:
                return 404, {}, b""
            obj = self.objects[key]
            rng = headers.get("Range")
            if rng:
                a, b = (int(x) for x in rng.split("=")[1].split("-"))
                msg = obj.get("chunks", {}).get(a, b"")
                return 206, {}, msg[: b - a + 1]
            return 200, {}, obj.get("bytes", b"")
        return 404, {}, b""


class RefetchTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name)
        shutil.copytree(FIXTURE / "history", self.root / "history")
        self.world = FakeWorld(self.root)
        self.clock = FakeClock(datetime(2026, 11, 11, 9, 25, tzinfo=timezone.utc))
        self.sink = LocalSink(str(self.root))
        self.v = Verifier(self.sink, Net(self.world, self.clock), self.clock, rng_seed=7)

    def run_one(self):
        todo = self.v.pending()
        self.assertEqual(len(todo), 1)
        batch, digest, path, ref = todo[0]
        return self.v.verify(batch, digest, ref), path

    def test_matching_sources_pass_and_report_is_keyed_by_manifest(self):
        self.assertEqual(check_batch(self.root, BATCH).failures, [])  # rewritten fixture is still valid
        report, path = self.run_one()
        self.assertEqual(report["failures"], [])
        self.assertTrue(report["ok"])
        self.assertTrue(path.startswith("verification/development/2026-09-11/"))
        ny = report["cities"]["NY"]
        self.assertTrue(ny["markets_match"] and ny["candles_match"])
        self.assertEqual(len(ny["sampled_hours"]), 3)
        self.assertTrue(all(h["sha256_match"] for h in ny["sampled_hours"]))
        self.assertTrue(all("TMP:2 m above ground" in h["idx_line"] for h in ny["sampled_hours"]))
        self.assertEqual(ny["later_complete_cycles"], [])

    def test_report_is_written_once_then_batch_is_no_longer_pending(self):
        report, path = self.run_one()
        self.sink.commit({path: json.dumps(report, default=str).encode()}, "x")
        self.assertEqual(self.v.pending(), [])
        # A revised batch (different manifest) is pending again.
        man = self.root / BATCH / "manifest.json"
        man.write_bytes(man.read_bytes() + b"\n")
        self.assertEqual(len(self.v.pending()), 1)

    # Los Angeles used the 23Z cycle for a 01Z cutoff, so the 00Z cycle is a later candidate.

    def test_later_complete_cycle_before_cutoff_fails(self):
        self.world.add_later_cycle("LAX", datetime(2026, 9, 11, 0, 55, tzinfo=timezone.utc))
        report, _ = self.run_one()
        self.assertTrue(any("later cycle" in f and f.startswith("LAX") for f in report["failures"]))
        self.assertEqual(report["cities"]["LAX"]["later_complete_cycles"], ["2026-09-11T00Z"])

    def test_later_cycle_published_after_cutoff_is_fine(self):
        self.world.add_later_cycle("LAX", datetime(2026, 9, 11, 1, 0, 1, tzinfo=timezone.utc))
        report, _ = self.run_one()
        self.assertEqual(report["cities"]["LAX"]["later_complete_cycles"], [])
        self.assertEqual(report["failures"], [])

    def test_different_grib_bytes_fail(self):
        nbm = json.loads((self.root / BATCH / "NY/nbm.json").read_bytes())
        for h in nbm["hours"]:
            chunks = self.world.objects[h["source"]["s3_key"]]["chunks"]
            for k in chunks:
                chunks[k] = chunks[k].replace(b"GRIB-", b"GRIX-")
        report, _ = self.run_one()
        self.assertTrue(any(f.startswith("NY") and "hash differs" in f for f in report["failures"]))

    def test_listing_that_disagrees_on_last_modified_fails(self):
        nbm = json.loads((self.root / BATCH / "MIA/nbm.json").read_bytes())
        key = nbm["hours"][0]["source"]["s3_key"]
        self.world.objects[key]["last_modified"] += timedelta(minutes=30)
        # Alter every MIA object so whichever hours get sampled, the change is seen.
        for h in nbm["hours"]:
            self.world.objects[h["source"]["s3_key"]]["last_modified"] = _utc(
                h["source"]["last_modified_utc"]) + timedelta(minutes=30)
        report, _ = self.run_one()
        self.assertTrue(any(f.startswith("MIA") and "listing differs" in f for f in report["failures"]))
        self.assertTrue(any(f.startswith("MIA") and "after the cutoff" in f for f in report["failures"]))

    def test_payout_changed_at_source_fails(self):
        man = json.loads((self.root / BATCH / "manifest.json").read_bytes())
        url = man["cities"]["CHI"]["kalshi_sources"]["markets"]["url"]
        live = json.loads(self.world.kalshi[url])
        live["markets"][0]["settlement_value_dollars"] = "0.5000"
        self.world.kalshi[url] = json.dumps(live).encode()
        report, _ = self.run_one()
        self.assertTrue(any(f.startswith("CHI") and "markets differ" in f for f in report["failures"]))

    def test_candle_changed_at_source_fails(self):
        man = json.loads((self.root / BATCH / "manifest.json").read_bytes())
        url = man["cities"]["DEN"]["kalshi_sources"]["candles"]["url"]
        live = json.loads(self.world.kalshi[url])
        live["markets"][0]["candlesticks"][-1]["yes_bid"]["close_dollars"] = "0.0100"
        live["markets"][0]["candlesticks"][-1]["end_period_ts"] = int(
            _utc(man["cities"]["DEN"]["cutoff_utc"]).timestamp())
        self.world.kalshi[url] = json.dumps(live).encode()
        report, _ = self.run_one()
        self.assertTrue(any(f.startswith("DEN") and "candles" in f for f in report["failures"]))

    def test_missing_source_is_a_confirmed_failure_not_a_crash(self):
        self.world.kalshi.clear()  # HTTP 404: the source answered, the data isn't there
        report, _ = self.run_one()
        self.assertEqual(report["status"], "failed")
        self.assertTrue(any("Kalshi re-fetch error" in f for f in report["failures"]))

    # --- found in ChatGPT #9 ---

    def test_branch_moving_after_discovery_is_never_certified(self):
        """LocalSink can't pin a commit, which makes it the worst case: the guard must catch it."""
        batch, digest, path, ref = self.v.pending()[0]
        man = self.root / BATCH / "manifest.json"
        man.write_bytes(man.read_bytes() + b"\n")  # the branch moves between discovery and download
        report = self.v.verify(batch, digest, ref)
        self.assertEqual(report["status"], "retry")
        self.assertTrue(any("expected " + digest in e for e in report["transient_errors"]))
        self.assertEqual(report["cities"], {})  # nothing was checked under the wrong manifest

    def test_pinned_snapshot_is_verified_even_if_the_branch_moves(self):
        sink = SnapshotSink(self.root)
        v = Verifier(sink, Net(self.world, self.clock), self.clock, rng_seed=7)
        batch, digest, path, ref = v.pending()[0]
        sink.move_branch(lambda files: files.__setitem__(
            f"{BATCH}/manifest.json", files[f"{BATCH}/manifest.json"] + b"\n"))
        report = v.verify(batch, digest, ref)
        self.assertEqual(report["status"], "ok")
        self.assertEqual(report["data_commit"], ref)
        # The moved manifest is a different batch version, so it is pending on its own.
        self.assertNotEqual(v.pending()[0][1], digest)

    def test_outage_then_recovery_keeps_the_batch_pending_until_verified(self):
        self.world.kalshi_503s = 4  # every try (4) of the first Kalshi request fails
        first = run_once(self.v, self.sink, "run1")
        self.assertEqual([r["status"] for r in first], ["retry"])
        self.assertTrue(first[0]["report"].startswith("verification/attempts/development/2026-09-11/"))
        self.assertIsNotNone(self.sink.read(first[0]["report"]))   # the outage is on record...
        self.assertEqual(len(self.v.pending()), 1)                  # ...and the batch is still queued
        self.assertFalse(any(p.startswith("verification/development/")
                             for p in self.sink.list_files("verification/")))
        second = run_once(self.v, self.sink, "run2")               # upstream recovered
        self.assertEqual([r["status"] for r in second], ["ok"])
        self.assertTrue(second[0]["report"].startswith("verification/development/2026-09-11/"))
        self.assertEqual(self.v.pending(), [])


class SnapshotSink:
    """A data repo with real commit snapshots: reads at a ref see that commit only."""

    def __init__(self, root: Path):
        files = {p.relative_to(root).as_posix(): p.read_bytes() for p in root.rglob("*") if p.is_file()}
        self.commits = {"c1": files}
        self.branch = "c1"

    def head(self):
        return self.branch

    def _files(self, ref):
        return self.commits[ref or self.branch]

    def read(self, path, ref=None):
        return self._files(ref).get(path)

    def list_files(self, prefix="", ref=None):
        return sorted(p for p in self._files(ref) if p.startswith(prefix))

    def move_branch(self, change):
        files = dict(self.commits[self.branch])
        change(files)
        new = f"c{len(self.commits) + 1}"
        self.commits[new] = files
        self.branch = new

    def commit(self, files, message):
        self.move_branch(lambda f: f.update(files))
        return self.branch


